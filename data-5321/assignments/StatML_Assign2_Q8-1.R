library(ISLR2)
attach(Auto)
linearR <- lm(mpg ~ horsepower)
summary(linearR)
new = data.frame(horsepower = 98)
predict(linearR, new, interval = "prediction", level = 0.95)
predict(linearR, new, interval = "confidence", level = 0.95)
plot(Auto$horsepower, Auto$mpg, main = "MPG vs Horsepower", xlab = "Horsepower", ylab = "MPG", col="green")
abline(lm(mpg~horsepower))
par(mfrow = c(2, 2))
plot(linearR)
